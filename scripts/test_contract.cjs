/* Supplementary real-EVM QA when Python EVM extensions are unavailable. */
const ganache=require(process.env.PQE_GANACHE || 'ganache');
const {ethers}=require(process.env.PQE_ETHERS || 'ethers');
const assert=require('node:assert/strict');
const artifact=require('../build/PQEscrow.json');
(async()=>{
 const transport=ganache.provider({logging:{quiet:true},wallet:{totalAccounts:5},chain:{hardfork:'shanghai'}});
 const provider=new ethers.BrowserProvider(transport);provider.pollingInterval=50;
 const [owner,buyer,seller,outsider]=await Promise.all([0,1,2,3].map(i=>provider.getSigner(i)));
 const factory=new ethers.ContractFactory(artifact.abi,artifact.bytecode,owner);
 const c=await factory.deploy(60);await c.waitForDeployment();
 const E=10n**18n,key='0x'+'a'.repeat(64),evidence='0x'+'b'.repeat(64),id='0x'+'1'.repeat(64);
 const ba=await buyer.getAddress(),sa=await seller.getAddress();
 const passed=[];
 async function blocked(label,fn){let failed=false;try{const tx=await fn();await tx.wait();}catch(e){failed=true;}assert(failed,label+' must revert');passed.push(label);}
 await (await c.connect(buyer).deposit(key,3600,{value:2n*E})).wait();
 await blocked('Minimum deposit lock',()=>c.connect(buyer).deposit(key,59,{value:1}));
 await blocked('Key cannot be replaced',()=>c.connect(buyer).deposit('0x'+'c'.repeat(64),60,{value:1}));
 await blocked('Withdraw blocked while locked',()=>c.connect(buyer).withdraw(E));
 await blocked('Only relayer can settle',()=>c.connect(outsider).settle(id,ba,sa,E,1,key,true,evidence));
 await blocked('Wrong key rejected',()=>c.settle(id,ba,sa,E,1,'0x'+'c'.repeat(64),true,evidence));
 await blocked('Insufficient balance rejected',()=>c.settle(id,ba,sa,3n*E,1,key,true,evidence));
 await (await c.settle(id,ba,sa,E,1,key,true,evidence)).wait();
 assert.equal(await c.claimable(sa),E);assert.equal((await c.accounts(ba)).balance,E);
 assert.equal((await c.settlements(id)).evidenceHash,evidence);passed.push('Release and evidence anchor');
 await blocked('Escrow replay rejected',()=>c.settle(id,ba,sa,E,2,key,true,evidence));
 await blocked('Sequence double spend rejected',()=>c.settle('0x'+'2'.repeat(64),ba,sa,E,1,key,true,evidence));
 const before=BigInt(await transport.request({method:'eth_getBalance',params:[sa,'latest']}));
 const claim=await (await c.connect(seller).claim()).wait();
 const after=BigInt(await transport.request({method:'eth_getBalance',params:[sa,'latest']}));
 assert.equal(after,before+E-claim.gasUsed*claim.gasPrice);assert.equal(await c.claimable(sa),0n);passed.push('Seller claim including exact gas cost');
 await (await c.settle('0x'+'3'.repeat(64),ba,sa,10n*E,2,key,false,evidence)).wait();
 assert.equal((await c.accounts(ba)).balance,E);assert.equal(await c.seqUsed(ba,2),true);passed.push('Refund consumes sequence without debiting balance');
 await transport.request({method:'evm_increaseTime',params:[3601]});await transport.request({method:'evm_mine',params:[]});
 await (await c.connect(buyer).withdraw(E,{gasLimit:100000})).wait();assert.equal((await c.accounts(ba)).balance,0n);passed.push('Withdraw succeeds after unlock');
 await blocked('Unauthorized relayer administration',()=>c.connect(outsider).setRelayer(sa,true));
 await (await c.setRelayer(sa,true)).wait();assert.equal(await c.relayers(sa),true);passed.push('Owner can authorize relayer');
 const fs=require('node:fs'),path=require('node:path'),solc=require('solc');
 const source=fs.readFileSync(path.resolve(__dirname,'../contracts/test/ReentrantReceiver.sol'),'utf8');
 const compiled=JSON.parse(solc.compile(JSON.stringify({language:'Solidity',sources:{'Receiver.sol':{content:source}},settings:{evmVersion:'paris',outputSelection:{'*':{'*':['abi','evm.bytecode.object']}}}})));
 const receiverSpec=compiled.contracts['Receiver.sol'].ReentrantReceiver;
 const receiver=await new ethers.ContractFactory(receiverSpec.abi,'0x'+receiverSpec.evm.bytecode.object,owner).deploy(await c.getAddress());await receiver.waitForDeployment();
 await (await receiver.fund({value:2n*E})).wait();
 await transport.request({method:'evm_increaseTime',params:[61]});await transport.request({method:'evm_mine',params:[]});
 await (await receiver.tryWithdraw()).wait();assert.equal(await receiver.attempted(),true);assert.equal(await receiver.blocked(),true);passed.push('Withdraw reentry blocked with unlocked funds remaining');
 await (await c.connect(buyer).deposit(key,60,{value:E})).wait();
 await (await c.settle('0x'+'4'.repeat(64),ba,await receiver.getAddress(),1,3,key,true,evidence)).wait();
 await (await receiver.tryClaim()).wait();assert.equal(await receiver.attempted(),true);assert.equal(await receiver.blocked(),true);passed.push('Claim-to-withdraw cross-function reentry blocked');
 const result={passed:true,engine:'Ganache in-process EVM',checks:passed};
 if(process.env.PQE_EVM_RESULTS)fs.writeFileSync(process.env.PQE_EVM_RESULTS,JSON.stringify(result,null,2));
 console.log(JSON.stringify(result,null,2));
 await transport.disconnect();
})().catch(error=>{console.error(error);process.exitCode=1;});
